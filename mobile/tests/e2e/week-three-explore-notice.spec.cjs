const { test, expect } = require("@playwright/test");
const { ids, savedAudit, install, signIn, accounts } = require("./helpers/week-three-handoff.cjs");
test("handoff draft survives failed save, access recheck and restart without generating synthetic events", async ({ page, context }) => {
  const { state, auth } = await install(context);
  const data = savedAudit();
  state.records.set(accounts.a.id, { activity_id: ids[3], status: "in_progress", current_step: "week_three_explore", started_at: data.practice_started_at, completed_at: null, updated_at: "seed", reflection_answers: { week_three_module_v1: JSON.stringify(data) } });
  await signIn(page);
  await page.getByRole("button", { name: "Resume: Explore", exact: true }).click();
  await page.clock.install();
  const topic = page.getByRole("textbox", { name: "Topic or trigger", exact: true });
  await topic.fill("  Kept after failures and restart  ");
  state.failAccess = true;
  await page.evaluate(() => {
    Object.defineProperty(document, "visibilityState", { configurable: true, value: "hidden" }); document.dispatchEvent(new Event("visibilitychange"));
    Object.defineProperty(document, "visibilityState", { configurable: true, value: "visible" }); document.dispatchEvent(new Event("visibilitychange"));
  });
  await expect(page.getByText(/Could not verify saved completion/)).toBeVisible();
  await expect(topic).not.toBeVisible();
  state.failAccess = false;
  await page.getByRole("button", { name: "Check week access again", exact: true }).click();
  await expect(topic).toHaveValue("  Kept after failures and restart  ");
  state.failSave = true;
  await page.getByRole("button", { name: "Save Week 3 draft", exact: true }).click();
  await expect(page.getByText(/Could not save Week 3. Your input is still here/)).toBeVisible();
  await expect(topic).toHaveValue("  Kept after failures and restart  ");
  await page.getByRole("button", { name: "Retry Week 3 save", exact: true }).click();
  await expect(page.getByText("Week 3 saved.", { exact: true })).toBeVisible();
  await page.reload(); await page.getByRole("button", { name: "Resume: Explore", exact: true }).click();
  await expect(topic).toHaveValue("  Kept after failures and restart  ");
  const saved = JSON.parse(state.records.get(accounts.a.id).reflection_answers.week_three_module_v1);
  expect(saved.entries).toEqual(data.entries); expect(saved.completed_at).toBeNull();
  expect(state.ai).toHaveLength(0); expect(auth.errors).toEqual([]);
});
